def text_width(s, tracking=0.10):
    """Advance width of a string in cap-height units."""
    n = 0.0
    for ch in s:
        g = GLYPHS.get(ch)
        gw = 0.70 if ch == "W" else (0.70 if ch == "M" else 0.62)
        n += gw + tracking
    return max(0.0, n - tracking)


def strokes_for(s, x, y, size, tracking=0.10):
    """Place each glyph's polylines in page space. y is the cap-top."""
    out = []
    cx = x
    for ch in s:
        g = GLYPHS.get(ch)
        gw = 0.70 if ch in ("W", "M") else 0.62
        if g:
            for stroke in g:
                pts = [(cx + px * size, y + py * size) for px, py in stroke]
                out.append((pts, gw))
        cx += gw * size + tracking * size
    return out
